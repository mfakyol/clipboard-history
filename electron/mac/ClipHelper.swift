// macOS counterpart of the PowerShell helper in winhelper.cjs: same line protocol, same commands.
// Built into a universal binary by scripts/build-mac-helper.cjs and shipped in the app's Resources.
//   seq        -> pasteboard change count (cheap change detection)
//   fg         -> pid of the frontmost app (to check where the user is)
//   info       -> "<hidden 0|1>|<name of the frontmost app>"
//   caret      -> "x,y,height" of the focused text caret (points, top-left origin), or "none"
//   focusrect  -> "x,y,w,h" of the focused UI element (points, top-left origin), or "none"
//   focus <p>  -> activate app <p>
//   paste <p>  -> wait until app <p> is frontmost and modifiers are released, send Cmd+V
//   watch 1|0  -> report mouse clicks while the palette is open
//   trusted    -> "1" if this process may use the Accessibility API, else "0"
// Unsolicited events start with "!":
//   !m <x> <y>  mouse button pressed while watching (points, top-left origin)
// caret, focusrect and paste need the Accessibility permission (granted to Clipboard History).

import ApplicationServices
import Cocoa

let outLock = NSLock()
func send(_ line: String) {
  outLock.lock()
  FileHandle.standardOutput.write((line + "\n").data(using: .utf8)!)
  outLock.unlock()
}

// Password managers mark sensitive copies with these types (nspasteboard.org convention).
let hiddenTypes: Set<String> = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "com.agilebits.onepassword",
]

func frontmost() -> NSRunningApplication? { NSWorkspace.shared.frontmostApplication }

func info() -> String {
  let types = NSPasteboard.general.types?.map { $0.rawValue } ?? []
  let hidden = types.contains { hiddenTypes.contains($0) }
  let app = frontmost()
  let name = app?.localizedName ?? app?.executableURL?.lastPathComponent ?? ""
  return (hidden ? "1" : "0") + "|" + name.replacingOccurrences(of: "\n", with: " ")
}

// The focused element of the frontmost app. Chromium-based apps build their accessibility tree
// only for assistive clients; AXManualAccessibility asks them to, without the side effects of
// AXEnhancedUserInterface. Calls are capped so a busy app can't stall the palette.
func focusedElement() -> AXUIElement? {
  guard let pid = frontmost()?.processIdentifier else { return nil }
  let app = AXUIElementCreateApplication(pid)
  AXUIElementSetMessagingTimeout(app, 0.4)
  AXUIElementSetAttributeValue(app, "AXManualAccessibility" as CFString, kCFBooleanTrue)
  var value: CFTypeRef?
  guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &value) == .success,
    let value, CFGetTypeID(value) == AXUIElementGetTypeID()
  else { return nil }
  let el = value as! AXUIElement
  AXUIElementSetMessagingTimeout(el, 0.4)
  return el
}

func axValue<T: BitwiseCopyable>(_ el: AXUIElement, _ attr: String, _ type: AXValueType, _ empty: T) -> T? {
  var value: CFTypeRef?
  guard AXUIElementCopyAttributeValue(el, attr as CFString, &value) == .success, let value,
    CFGetTypeID(value) == AXValueGetTypeID()
  else { return nil }
  var out = empty
  return AXValueGetValue(value as! AXValue, type, &out) ? out : nil
}

func focusRect() -> String {
  guard let el = focusedElement(),
    let p = axValue(el, kAXPositionAttribute, .cgPoint, CGPoint.zero),
    let s = axValue(el, kAXSizeAttribute, .cgSize, CGSize.zero),
    s.width > 0, s.height > 0
  else { return "none" }
  return "\(Int(p.x)),\(Int(p.y)),\(Int(s.width)),\(Int(s.height))"
}

func caret() -> String {
  guard let el = focusedElement(),
    var range = axValue(el, kAXSelectedTextRangeAttribute, .cfRange, CFRange())
  else { return "none" }
  // Some apps return an empty rect for a zero-length range; the next character works there.
  for length in [range.length, 1] {
    range.length = length
    guard let param = AXValueCreate(.cfRange, &range) else { continue }
    var value: CFTypeRef?
    guard AXUIElementCopyParameterizedAttributeValue(
      el, kAXBoundsForRangeParameterizedAttribute as CFString, param, &value) == .success,
      let value, CFGetTypeID(value) == AXValueGetTypeID()
    else { continue }
    var r = CGRect.zero
    if AXValueGetValue(value as! AXValue, .cgRect, &r), r.height > 0 {
      return "\(Int(r.minX)),\(Int(r.minY)),\(Int(r.height))"
    }
  }
  return "none"
}

// A background process may not activate another app (cooperative activation, macOS 14+), but an
// accessibility client may raise it by setting AXFrontmost; plain activate() is the fallback.
func activate(_ pid: pid_t) -> Bool {
  guard let app = NSRunningApplication(processIdentifier: pid) else { return false }
  if app.isActive { return true }
  let el = AXUIElementCreateApplication(pid)
  if AXUIElementSetAttributeValue(el, kAXFrontmostAttribute as CFString, kCFBooleanTrue) != .success {
    app.activate(options: [])
  }
  for _ in 0..<30 where !app.isActive { usleep(10_000) }
  return app.isActive
}

func paste(_ pid: pid_t) {
  // Wait for the target to be frontmost again (search mode hands focus back just before this).
  for _ in 0..<60 where frontmost()?.processIdentifier != pid { usleep(10_000) }
  // Shift still held from Shift+click would turn this into Cmd+Shift+V and reopen the palette.
  let held: CGEventFlags = [.maskShift, .maskControl, .maskAlternate, .maskCommand]
  for _ in 0..<150 where !CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty {
    usleep(10_000)
  }
  usleep(40_000)
  let src = CGEventSource(stateID: .combinedSessionState)
  let v: CGKeyCode = 9 // kVK_ANSI_V
  let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
  let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
  down?.flags = .maskCommand
  up?.flags = .maskCommand
  down?.post(tap: .cghidEventTap)
  up?.post(tap: .cghidEventTap)
}

// The palette never becomes key, so it never sees a click elsewhere; report clicks while it's open.
// A global monitor only observes, so the click still reaches its target.
var monitor: Any?
func watch(_ on: Bool) {
  if on, monitor == nil {
    monitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown, .otherMouseDown]) { _ in
      let p = NSEvent.mouseLocation
      let top = NSScreen.screens.first?.frame.maxY ?? 0 // Cocoa is bottom-left, Electron top-left
      send("!m \(Int(p.x)) \(Int(top - p.y))")
    }
  } else if !on, let m = monitor {
    NSEvent.removeMonitor(m)
    monitor = nil
  }
}

func handle(_ line: String) -> String {
  let parts = line.trimmingCharacters(in: .whitespaces).split(separator: " ").map(String.init)
  let arg = parts.count > 1 ? pid_t(parts[1]) ?? 0 : 0
  switch parts.first ?? "" {
  case "seq": return String(NSPasteboard.general.changeCount)
  case "trusted": return AXIsProcessTrusted() ? "1" : "0"
  case "fg": return String(frontmost()?.processIdentifier ?? 0)
  case "info": return info()
  case "caret": return caret()
  case "focusrect": return focusRect()
  case "focus": return activate(arg) ? "True" : "False"
  case "paste":
    paste(arg)
    return "ok"
  case "watch":
    watch(parts.count > 1 && parts[1] == "1")
    return "ok"
  default: return "unknown"
  }
}

let app = NSApplication.shared
app.setActivationPolicy(.prohibited)

// stdin on a background thread; commands run on the main thread, where AppKit state is updated.
Thread {
  while let line = readLine() {
    let reply = DispatchQueue.main.sync { handle(line) }
    send(reply)
  }
  exit(0)
}.start()

send("ready")
app.run()
